export interface LabValue {
  code: string;
  name: string;
  value: number;
  unit: string;
  /** Reference range exactly as printed on the user's report. Never generated by Forge. */
  refText?: string;
}

export interface LabReport {
  id: string;
  /** Sample collection date, YYYY-MM-DD. */
  date: string;
  lab: string;
  values: LabValue[];
  doctorConfirmed: boolean;
  doctorName?: string;
  confirmedOn?: string;
  createdAt: string;
}

export interface LabReportInput {
  date: string;
  lab: string;
  values: Array<{ code: string; name: string; value: number | null; unit: string; refText?: string }>;
}

const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

function isRealDate(s: string): boolean {
  if (!DATE_RE.test(s)) return false;
  const [y, m, d] = s.split('-').map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === m - 1 && dt.getUTCDate() === d;
}

/** Returns a list of problems; empty means the input can be saved. */
export function validateReportInput(input: LabReportInput, today: string): string[] {
  const errors: string[] = [];
  if (!isRealDate(input.date)) errors.push('Enter the sample date.');
  else if (input.date > today) errors.push('The sample date cannot be in the future.');
  if (!input.lab.trim()) errors.push('Enter the lab name from the report.');
  const filled = input.values.filter((v) => v.value !== null);
  if (filled.length === 0) errors.push('Enter at least one value.');
  for (const v of filled) {
    if (!Number.isFinite(v.value as number) || (v.value as number) < 0) {
      errors.push(`${v.name}: enter a number of 0 or more.`);
    }
    if (!v.unit.trim()) errors.push(`${v.name}: enter the unit from the report.`);
    if (!v.name.trim()) errors.push('Every value needs a marker name.');
  }
  const codes = filled.map((v) => v.code);
  if (new Set(codes).size !== codes.length) errors.push('A marker is entered twice.');
  return errors;
}

function sortReports(reports: LabReport[]): LabReport[] {
  return [...reports].sort((a, b) =>
    a.date === b.date ? a.createdAt.localeCompare(b.createdAt) : a.date.localeCompare(b.date)
  );
}

/** Adds a report as NOT confirmed. Throws if the input is invalid. */
export function addReport(
  reports: LabReport[],
  input: LabReportInput,
  opts: { id: string; now: string; today: string }
): LabReport[] {
  const errors = validateReportInput(input, opts.today);
  if (errors.length > 0) throw new Error(errors[0]);
  const report: LabReport = {
    id: opts.id,
    date: input.date,
    lab: input.lab.trim(),
    values: input.values
      .filter((v) => v.value !== null)
      .map((v) => ({
        code: v.code,
        name: v.name.trim(),
        value: v.value as number,
        unit: v.unit.trim(),
        ...(v.refText && v.refText.trim() ? { refText: v.refText.trim() } : {}),
      })),
    doctorConfirmed: false,
    createdAt: opts.now,
  };
  return sortReports([...reports, report]);
}

/** Records that a named doctor reviewed the report. A doctor name is required. */
export function confirmReport(
  reports: LabReport[],
  id: string,
  doctorName: string,
  confirmedOn: string
): LabReport[] {
  const name = doctorName.trim();
  if (!name) throw new Error("Enter the doctor's name.");
  if (!reports.some((r) => r.id === id)) throw new Error('Report not found.');
  return reports.map((r) =>
    r.id === id ? { ...r, doctorConfirmed: true, doctorName: name, confirmedOn } : r
  );
}

export function unconfirmReport(reports: LabReport[], id: string): LabReport[] {
  return reports.map((r) => {
    if (r.id !== id) return r;
    const { doctorName: _n, confirmedOn: _c, ...rest } = r;
    return { ...rest, doctorConfirmed: false };
  });
}

export function removeReport(reports: LabReport[], id: string): LabReport[] {
  return reports.filter((r) => r.id !== id);
}

export interface MarkerComparison {
  code: string;
  name: string;
  unit: string;
  first: { date: string; value: number };
  latest: { date: string; value: number } | null;
  /** latest minus first, rounded to 2 decimals. null with one report or when units differ. */
  delta: number | null;
  unitsDiffer: boolean;
}

/** Start versus latest, using doctor-confirmed reports only. No judgement of the change. */
export function compareMarkers(reports: LabReport[]): MarkerComparison[] {
  const confirmed = sortReports(reports.filter((r) => r.doctorConfirmed));
  const byCode = new Map<string, Array<{ date: string; v: LabValue }>>();
  for (const r of confirmed) {
    for (const v of r.values) {
      const list = byCode.get(v.code) ?? [];
      list.push({ date: r.date, v });
      byCode.set(v.code, list);
    }
  }
  const out: MarkerComparison[] = [];
  for (const [code, list] of byCode) {
    const first = list[0];
    const last = list.length > 1 ? list[list.length - 1] : null;
    const unitsDiffer = !!last && last.v.unit.toLowerCase() !== first.v.unit.toLowerCase();
    out.push({
      code,
      name: first.v.name,
      unit: first.v.unit,
      first: { date: first.date, value: first.v.value },
      latest: last ? { date: last.date, value: last.v.value } : null,
      delta: last && !unitsDiffer ? Math.round((last.v.value - first.v.value) * 100) / 100 : null,
      unitsDiffer,
    });
  }
  return out;
}

function isLabReport(x: unknown): x is LabReport {
  if (!x || typeof x !== 'object') return false;
  const r = x as Record<string, unknown>;
  return (
    typeof r.id === 'string' &&
    typeof r.date === 'string' &&
    typeof r.lab === 'string' &&
    typeof r.createdAt === 'string' &&
    typeof r.doctorConfirmed === 'boolean' &&
    Array.isArray(r.values) &&
    r.values.every(
      (v) =>
        v &&
        typeof v === 'object' &&
        typeof (v as LabValue).code === 'string' &&
        typeof (v as LabValue).name === 'string' &&
        typeof (v as LabValue).unit === 'string' &&
        Number.isFinite((v as LabValue).value)
    )
  );
}

type StorageLike = Pick<Storage, 'getItem' | 'setItem'>;

/** Reads reports. Anything unreadable or malformed is dropped, never thrown. */
export function loadReports(storage: StorageLike): LabReport[] {
  try {
    const raw = storage.getItem(LAB_STORAGE_KEY);
    if (!raw) return [];
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return sortReports(parsed.filter(isLabReport));
  } catch {
    return [];
  }
}

/** Returns false when the device refused the write (for example storage full). */
export function saveReports(storage: StorageLike, reports: LabReport[]): boolean {
  try {
    storage.setItem(LAB_STORAGE_KEY, JSON.stringify(reports));
    return true;
  } catch {
    return false;
  }
}
