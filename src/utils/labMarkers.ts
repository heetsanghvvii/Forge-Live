/**
 * Lab markers: a place to record blood test results a doctor has ordered, and to compare
 * a start report with a later one once a doctor has confirmed them.
 *
 * Product rules enforced here:
 * - Forge never chooses tests and never interprets a value. No ranges, flags or scores are
 *   generated; a reference range is only ever the text the user copies from their own report.
 * - A report counts in comparisons only after the user records that a doctor reviewed it.
 * - Reports live in their own localStorage key on this device. They are not part of AppState
 *   and are never sent to the cloud.
 */

export const LAB_STORAGE_KEY = 'forge_lab_reports_v1';

